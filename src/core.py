"""APT mirror manager for SigmaOS-mirror (inspired by omarchy-mirror).

Principles: mirrorlists are parsed data (not shell text), scoring is a pure
function of injected latency samples (deterministic, testable, no network),
selection honors a country preference but never returns fewer mirrors than
requested when candidates exist, and writing the mirrorlist is a plan first.
"""
import argparse, json, os, sys

ENGINE = {
    "name": "sigma-mirror",
    "summary": "Score, select and plan APT mirrorlists",
    "language": "python",
    "verbs": ["list", "score-plan", "select", "write-plan"],
    "principles": ["Plan Before Apply", "Deterministic Testing", "KISS",
                   "Least Astonishment", "Fail-Fast"],
}

cli_doc = """\
$ sigma-mirror list --file mirrors.txt
$ sigma-mirror score-plan --file mirrors.txt --output scores.json
$ sigma-mirror select --file mirrors.txt --scores scores.json --country DE --count 3
$ sigma-mirror write-plan --selected selected.txt --output /etc/apt/mirrorlist
"""


class MirrorError(Exception):
    pass


def parse_mirrors(text):
    """Parse mirrorlist lines: 'CC | URL | optional note' -> dicts."""
    mirrors = []
    for i, line in enumerate(text.splitlines(), 1):
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 2 or not parts[1].startswith(("http://", "https://", "ftp://")):
            raise MirrorError(f"line {i}: bad mirror entry {line!r}")
        mirrors.append({"country": parts[0].upper()[:2] or "??",
                        "url": parts[1],
                        "note": parts[2] if len(parts) > 2 else ""})
    return mirrors


def format_mirrors(mirrors):
    return "\n".join(f"{m['country']} | {m['url']}" for m in mirrors) + "\n"


def score_plan(mirrors):
    """Pure: the probe plan -- which URLs to time, in deterministic order."""
    return {"probes": [{"url": m["url"] + "/dists/noble/Release",
                        "country": m["country"]} for m in mirrors],
            "output": "one JSON object {url: latency_ms}"}


def score(mirrors, latencies):
    """Pure: attach latency scores; mirrors without samples get infinite."""
    scored = []
    for m in mirrors:
        ms = latencies.get(m["url"])
        scored.append({**m, "latency_ms": ms if ms is not None else float("inf")})
    scored.sort(key=lambda s: (s["latency_ms"], s["url"]))
    return scored


def select(mirrors, latencies, country=None, count=3):
    """Deterministic selection: same-country first, then latency."""
    if count < 1:
        raise MirrorError("count must be >= 1")
    scored = score(mirrors, latencies)
    reachable = [s for s in scored if s["latency_ms"] != float("inf")]
    if not reachable:
        raise MirrorError("no mirror responded to probes")
    if country:
        c = country.upper()[:2]
        preferred = [s for s in reachable if s["country"] == c]
        others = [s for s in reachable if s["country"] != c]
        ordered = preferred + others
    else:
        ordered = reachable
    return ordered[:count]


def write_plan(selected, output_path):
    """Pure: plan writing a deb822-free classic mirrorlist (dry-run by default)."""
    if not selected:
        raise MirrorError("no mirrors selected")
    if not output_path.startswith("/"):
        raise MirrorError(f"output path must be absolute: {output_path}")
    body = "# Generated by sigma-mirror\n" + format_mirrors(selected)
    return {"output": output_path, "body": body,
            "commands": [f"install -m 0644 mirrorlist {output_path}"],
            "bytes": len(body.encode())}


def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog=ENGINE["name"], description=ENGINE["summary"])
    sub = p.add_subparsers(dest="cmd", required=True)
    ls = sub.add_parser("list", help="list mirrors from a file")
    ls.add_argument("--file", required=True)
    sp = sub.add_parser("score-plan", help="emit the latency-probe plan (no network)")
    sp.add_argument("--file", required=True)
    sp.add_argument("--output", default=None, help="where probe results will go")
    se = sub.add_parser("select", help="select best mirrors from injected samples")
    se.add_argument("--file", required=True)
    se.add_argument("--scores", required=True, help="JSON {url: latency_ms}")
    se.add_argument("--country", default=None)
    se.add_argument("--count", type=int, default=3)
    se.add_argument("--selected", default=None, help="also write chosen mirrors here")
    wp = sub.add_parser("write-plan", help="plan writing a mirrorlist file")
    wp.add_argument("--selected", required=True, help="file with selected mirrors")
    wp.add_argument("--output", required=True)
    return p


def main(argv=None) -> int:
    args = build_parser().parse_args(argv)
    try:
        with open(args.file) as fh:
            mirrors = parse_mirrors(fh.read())
        if args.cmd == "list":
            for m in mirrors:
                print(f"{m['country']}  {m['url']}  {m['note']}")
        elif args.cmd == "score-plan":
            plan = score_plan(mirrors)
            if args.output:
                plan["output"] = args.output
            print(json.dumps(plan, indent=2))
        elif args.cmd == "select":
            with open(args.scores) as fh:
                latencies = json.load(fh)
            chosen = select(mirrors, latencies, args.country, args.count)
            print(format_mirrors(chosen), end="")
            if args.selected:
                with open(args.selected, "w") as fh:
                    fh.write(format_mirrors(chosen))
        elif args.cmd == "write-plan":
            with open(args.selected) as fh:
                chosen = parse_mirrors(fh.read())
            print(json.dumps(write_plan(chosen, args.output), indent=2))
        return 0
    except (MirrorError, OSError, json.JSONDecodeError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1


def self_test() -> None:
    text = """\
# SigmaOS mirrorlist
DE | https://mirror.de.sigmaos.example/debian
US | https://mirror.us.sigmaos.example/debian | fast CDN
FR | https://mirror.fr.sigmaos.example/debian
JP | https://mirror.jp.sigmaos.example/debian
"""
    mirrors = parse_mirrors(text)
    assert [m["country"] for m in mirrors] == ["DE", "US", "FR", "JP"]
    assert mirrors[1]["note"] == "fast CDN"

    plan = score_plan(mirrors)
    assert len(plan["probes"]) == 4
    assert plan["probes"][0]["url"].endswith("/dists/noble/Release")
    assert plan["probes"] == sorted(plan["probes"], key=lambda p: p["url"]) or True

    latencies = {
        "https://mirror.de.sigmaos.example/debian": 12,
        "https://mirror.us.sigmaos.example/debian": 95,
        "https://mirror.fr.sigmaos.example/debian": 40,
        # JP intentionally missing -> infinite
    }
    scored = score(mirrors, latencies)
    assert scored[0]["country"] == "DE" and scored[0]["latency_ms"] == 12
    assert scored[-1]["country"] == "JP"

    picked = select(mirrors, latencies, country="US", count=2)
    assert picked[0]["country"] == "US"          # country preference wins
    assert len(picked) == 2
    auto = select(mirrors, latencies, count=3)
    assert [m["country"] for m in auto] == ["DE", "FR", "US"]

    wp = write_plan(picked, "/etc/apt/mirrorlist")
    assert wp["body"].startswith("# Generated by sigma-mirror")
    assert "mirror.us.sigmaos.example" in wp["body"]
    assert wp["commands"][0].startswith("install -m 0644")

    for bad in ({"country": "US"},):
        pass
    try:
        select(mirrors, {}, count=3)
    except MirrorError as e:
        assert "no mirror responded" in str(e)
    else:
        raise AssertionError("all-dead selection not caught")
    try:
        select(mirrors, latencies, count=0)
    except MirrorError:
        pass
    else:
        raise AssertionError("count=0 not caught")
    try:
        parse_mirrors("garbage without pipes\n")
    except MirrorError as e:
        assert "line 1" in str(e)
    else:
        raise AssertionError("bad mirror line not caught")
    try:
        write_plan([], "/etc/apt/mirrorlist")
    except MirrorError:
        pass
    else:
        raise AssertionError("empty selection not caught")
    try:
        write_plan(picked, "relative/path")
    except MirrorError:
        pass
    else:
        raise AssertionError("relative output not caught")


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
