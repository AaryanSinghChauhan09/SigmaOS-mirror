//! SigmaOS-mirror — Arch Linux mirrorlist / reflector parity.
//!
//! Inspired by `reflector` and `pacman-mirrorlist`: rank mirrors by
//! measured latency, filter by protocol/country/status, and emit a
//! pacman-compatible mirrorlist.

/// Mirror protocol — reflector ranks https first when score ties.
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
pub enum Protocol {
    Http,
    Https,
    Rsync,
}

/// Mirror health as reported by a status check (like Arch's mirror status page).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum MirrorStatus {
    Online,
    Offline,
    Unknown,
}

#[derive(Debug, Clone)]
pub struct MirrorEntry {
    pub url: String,
    pub country_code: String,
    pub ping_ms: u32,
    pub protocol: Protocol,
    pub status: MirrorStatus,
    /// Download throughput sample in KiB/s; 0 = untested.
    pub speed_kib: u32,
}

#[derive(Debug, Default)]
pub struct MirrorManager {
    mirrors: Vec<MirrorEntry>,
}

impl MirrorManager {
    pub fn new() -> Self {
        Self { mirrors: Vec::new() }
    }

    /// Full-fidelity registration; prefer this over `add_mirror`.
    pub fn add(&mut self, entry: MirrorEntry) {
        self.mirrors.push(entry);
    }

    /// Backwards-compatible shorthand (https assumed, status unknown).
    pub fn add_mirror(&mut self, url: &str, country: &str, ping: u32) {
        self.mirrors.push(MirrorEntry {
            url: url.into(),
            country_code: country.into(),
            ping_ms: ping,
            protocol: Protocol::Https,
            status: MirrorStatus::Unknown,
            speed_kib: 0,
        });
    }

    /// Keep only mirrors matching `country` (ISO-3166 alpha-2, case-insensitive)
    /// and `protocol` when `Some`.
    pub fn filter(&mut self, country: Option<&str>, protocol: Option<Protocol>) {
        self.mirrors.retain(|m| {
            let country_ok = country
                .map(|c| m.country_code.eq_ignore_ascii_case(c))
                .unwrap_or(true);
            let proto_ok = protocol.map(|p| m.protocol == p).unwrap_or(true);
            country_ok && proto_ok
        });
    }

    /// reflector-style scoring: lower is better.
    /// score = ping_ms - speed bonus; offline mirrors are excluded upstream.
    fn score(m: &MirrorEntry) -> u64 {
        let speed_bonus = (m.speed_kib as u64) / 500; // ~500KiB/s ≈ 1ms equivalent
        (m.ping_ms as u64).saturating_sub(speed_bonus)
    }

    /// Fastest usable mirror: online/unknown only, sorted by score.
    pub fn fastest_mirror(&self) -> Option<&MirrorEntry> {
        self.mirrors
            .iter()
            .filter(|m| m.status != MirrorStatus::Offline)
            .min_by_key(|m| Self::score(m))
    }

    /// Top-N mirror ranking, best first (like `reflector --sort rate`).
    pub fn ranked(&self, n: usize) -> Vec<&MirrorEntry> {
        let mut v: Vec<&MirrorEntry> = self
            .mirrors
            .iter()
            .filter(|m| m.status != MirrorStatus::Offline)
            .collect();
        v.sort_by_key(|m| Self::score(m));
        v.truncate(n);
        v
    }

    /// Generate a pacman-compatible mirrorlist (Server = ... lines).
    pub fn to_mirrorlist(&self, n: usize) -> String {
        let mut out = String::from("# Generated by SigmaOS-mirror\n");
        for m in self.ranked(n) {
            out.push_str(&format!("Server = {}\n", m.url));
        }
        out
    }

    pub fn len(&self) -> usize {
        self.mirrors.len()
    }

    pub fn is_empty(&self) -> bool {
        self.mirrors.is_empty()
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn entry(url: &str, cc: &str, ping: u32, proto: Protocol, status: MirrorStatus, speed: u32) -> MirrorEntry {
        MirrorEntry {
            url: url.into(),
            country_code: cc.into(),
            ping_ms: ping,
            protocol: proto,
            status,
            speed_kib: speed,
        }
    }

    #[test]
    fn test_mirror_manager_fastest_aaa() {
        let mut mgr = MirrorManager::new();
        mgr.add_mirror("https://us.repo.sigmaos.org", "US", 110);
        mgr.add_mirror("https://in.repo.sigmaos.org", "IN", 15);
        mgr.add_mirror("https://eu.repo.sigmaos.org", "DE", 85);
        let fastest = mgr.fastest_mirror().expect("Fastest mirror should exist");
        assert_eq!(fastest.country_code, "IN");
        assert_eq!(fastest.ping_ms, 15);
    }

    #[test]
    fn offline_mirrors_are_excluded() {
        let mut mgr = MirrorManager::new();
        mgr.add(entry("https://dead.example", "US", 1, Protocol::Https, MirrorStatus::Offline, 0));
        mgr.add(entry("https://live.example", "DE", 90, Protocol::Https, MirrorStatus::Online, 0));
        assert_eq!(mgr.fastest_mirror().unwrap().url, "https://live.example");
        assert_eq!(mgr.ranked(5).len(), 1);
    }

    #[test]
    fn speed_bonus_beats_raw_ping() {
        let mut mgr = MirrorManager::new();
        // 50ms ping but very fast vs 10ms ping slow
        mgr.add(entry("https://fast.example", "US", 50, Protocol::Https, MirrorStatus::Online, 100_000));
        mgr.add(entry("https://slow.example", "US", 10, Protocol::Https, MirrorStatus::Online, 0));
        let top = mgr.fastest_mirror().unwrap();
        // score(fast)=50-200=0(sat) vs score(slow)=10 -> fast wins
        assert_eq!(top.url, "https://fast.example");
    }

    #[test]
    fn country_and_protocol_filter() {
        let mut mgr = MirrorManager::new();
        mgr.add(entry("https://de1", "DE", 20, Protocol::Https, MirrorStatus::Online, 0));
        mgr.add(entry("https://de2", "de", 30, Protocol::Http, MirrorStatus::Online, 0));
        mgr.add(entry("https://us1", "US", 10, Protocol::Https, MirrorStatus::Online, 0));
        mgr.filter(Some("DE"), Some(Protocol::Https));
        assert_eq!(mgr.len(), 1);
        assert_eq!(mgr.fastest_mirror().unwrap().url, "https://de1");
    }

    #[test]
    fn mirrorlist_format() {
        let mut mgr = MirrorManager::new();
        mgr.add_mirror("https://a.example", "US", 10);
        mgr.add_mirror("https://b.example", "IN", 20);
        let ml = mgr.to_mirrorlist(2);
        assert!(ml.contains("Server = https://a.example"));
        assert!(ml.contains("Server = https://b.example"));
        assert!(ml.find("a.example").unwrap() < ml.find("b.example").unwrap());
    }
}
